// Fallback accuracy check. Compares MemLens fallback-table
// layouts against the compiler oracle (fixtures/truth/*.json) and writes
// docs/reports/fallback-accuracy.md. The TRUTH side comes from real compilers;
// this script only evaluates MemLens output against it (not self-grading:
// no test asserts on this report; tests assert exact match on a hand-picked
// supported subset in layout-truth.test.ts).
// Usage: node scripts/check-fallback-accuracy.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const { RegexParser } = await import("../packages/analysis/dist/parser.js");
const { getLayouts } = await import("../packages/analysis/dist/layout.js");
const { builtinTypeInfo } = await import("../packages/analysis/dist/sizes.js");

const truthDir = join(root, "fixtures", "truth");
const truthFiles = readdirSync(truthDir).filter((f) => f.endsWith(".json"));
if (truthFiles.length === 0) {
  console.error("No truth files. Run node scripts/gen-layout-truth.mjs first.");
  process.exit(2);
}

const tu = readFileSync(join(here, "layout-truth", "probes-clean.cpp"), "utf8");
const parsed = new RegexParser().parseFull(tu, "probes-clean");
const { layouts, accurate } = await getLayouts(tu, parsed.records, { compilerPath: "definitely-not-a-compiler-xyz" });

const rows = [];
for (const file of truthFiles) {
  const truth = JSON.parse(readFileSync(join(truthDir, file), "utf8"));
  for (const [probe, want] of Object.entries(truth)) {
    if (probe === "abi" || probe === "provenance" || probe === "P_Fund") continue;
    if (probe.startsWith("std::")) {
      const base = probe.split("<")[0];
      const got = builtinTypeInfo(base === "std::map" ? "std::map" : probe);
      const match = got !== null && got.size === want.sizeof && got.align === want.align;
      rows.push({ file, probe, kind: "container-size", want: `${want.sizeof}B/a${want.align}`, got: got ? `${got.size}B/a${got.align}` : "unknown", match, note: `stdlib is ${truth.abi.stdlib}` });
      continue;
    }
    if (probe === "P_Bits") {
      const refused = !layouts.has("P_Bits");
      rows.push({ file, probe, kind: "refusal", want: "refused (no offsetof on bit-fields)", got: refused ? "refused" : "emitted", match: refused, note: "" });
      continue;
    }
    const got = layouts.get(probe);
    if (!got) {
      rows.push({ file, probe, kind: "refusal", want: `sizeof=${want.sizeof}`, got: "refused (no fallback layout)", match: "n/a", note: "honest refusal; model uses symbolic sizeof" });
      continue;
    }
    const wantFields = Object.entries(want).filter(([k]) => k !== "sizeof" && k !== "align");
    const mism = [];
    if (got.totalSize !== want.sizeof) mism.push(`sizeof ${got.totalSize}≠${want.sizeof}`);
    if (got.align !== want.align) mism.push(`align ${got.align}≠${want.align}`);
    for (const [fname, f] of wantFields) {
      const g = got.fields.find((x) => x.name === fname);
      if (!g) mism.push(`missing field ${fname}`);
      else if (g.offset !== f.offset || g.size !== f.size) mism.push(`${fname}: off ${g.offset}≠${f.offset} size ${g.size}≠${f.size}`);
    }
    rows.push({ file, probe, kind: "layout", want: `sizeof=${want.sizeof}`, got: `sizeof=${got.totalSize}`, match: mism.length === 0, note: mism.join("; ") });
  }
}

const matched = rows.filter((r) => r.match === true).length;
const mismatched = rows.filter((r) => r.match === false).length;
const na = rows.filter((r) => r.match === "n/a").length;
let md = `# Fallback-table accuracy vs compiler truth\n\nGenerated by \`scripts/check-fallback-accuracy.mjs\` — MemLens fallback layouts evaluated against \`fixtures/truth/*.json\` (real compilers). Not a test oracle: it documents measured behavior.\n\n- Layout engine used fallback: ${!accurate}\n- Exact matches: ${matched}, mismatches: ${mismatched}, honest refusals: ${na}\n\n| truth file | probe | kind | want | fallback got | match | note |\n|---|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.file} | ${r.probe} | ${r.kind} | ${r.want} | ${r.got} | ${r.match} | ${r.note} |\n`;
mkdirSync(join(root, "docs", "reports"), { recursive: true });
writeFileSync(join(root, "docs", "reports", "fallback-accuracy.md"), md);
console.log(`accuracy: ${matched} match / ${mismatched} mismatch / ${na} refused (${rows.length} rows) → docs/reports/fallback-accuracy.md`);
